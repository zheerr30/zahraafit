"""Muscle-map images of the exercise cards, from renders of the application's own 3D model.

  1. render (e2e/render-maps.cjs, then e2e/render-maps-deep.cjs for deep muscles, Playwright on a running build of the app):
     the atlas, front and back, once plain and once per muscle group with that group
     lit by the exercise spotlight -> <raw>/base-<view>.png, <raw>/<group>-<view>.png
  2. this script: one crop for all images (the figure, 5:11), and per group a transparent
     overlay holding only the pixels the spotlight changed. The cards stack the overlays of
     an exercise's groups on the base image (components/exercise/MuscleMap.tsx).

  python3 pipeline/exercises/maps.py <raw dir> public/exercise-maps data/exercises/maps.ts
"""
import sys, os, glob
from PIL import Image, ImageChops, ImageFilter

raw, out, manifest = sys.argv[1:4]
os.makedirs(out, exist_ok=True)
H, W = 440, 200

bases = {v: Image.open(f"{raw}/base-{v}.png").convert("RGB") for v in ("front", "back")}

def figure_box(im):
    r, g, b = im.split()
    sat = ImageChops.difference(ImageChops.lighter(ImageChops.lighter(r, g), b), ImageChops.darker(ImageChops.darker(r, g), b))
    mask = sat.point(lambda x: 255 if x > 26 else 0).filter(ImageFilter.MedianFilter(5))
    # the tool bar at the bottom of the viewport is not part of the figure
    w, h = im.size
    mask.paste(0, (0, int(h * 0.9), w, h))
    return mask.getbbox()

boxes = [figure_box(b) for b in bases.values()]
top, bottom = min(b[1] for b in boxes), max(b[3] for b in boxes)
pad = int((bottom - top) * 0.035)
top, bottom = max(0, top - pad), bottom + pad
height = bottom - top
width = round(height * W / H)
cx = bases["front"].size[0] // 2
crop = (cx - width // 2, top, cx - width // 2 + width, bottom)
print("crop", crop, "figure boxes", boxes)

def fit(im):
    return im.crop(crop).resize((W, H), Image.LANCZOS)

for v, im in bases.items():
    fit(im).save(f"{out}/base-{v}.webp", quality=82, method=6)

# Deep muscles: a second render pass removes the covering layers ("@d2" no superficial
# muscles, "@d3" deep only, "@nt" no tendons / aponeuroses), each with its own plain base.
# Their overlay is still stacked on the normal base: the muscle shows through the surface.
TAGS = ["", "@d2", "@d3", "@nt"]
SEEN, MIN = 0.003, 0.0003  # share of the picture: clearly seen on the surface / worth showing at all

def overlay(name, tag):
    view = name.rsplit("-", 1)[1]
    lit_path, base_path = f"{raw}/{name}{tag}.png", f"{raw}/base-{view}{tag}.png"
    if not (os.path.exists(lit_path) and os.path.exists(base_path)):
        return None
    lit, base = Image.open(lit_path).convert("RGB").crop(crop), Image.open(base_path).convert("RGB").crop(crop)
    r, g, b = ImageChops.difference(lit, base).split()
    diff = ImageChops.lighter(ImageChops.lighter(r, g), b)
    alpha = diff.point(lambda x: 0 if x < 12 else min(255, (x - 12) * 12)).filter(ImageFilter.GaussianBlur(0.8))
    share = alpha.point(lambda x: 255 if x > 128 else 0).histogram()[255] / (alpha.size[0] * alpha.size[1])
    rgba = lit.convert("RGBA")
    rgba.putalpha(alpha)
    return share, rgba

kept, dropped = [], []
names = sorted({os.path.basename(p)[:-4].split("@")[0] for p in glob.glob(f"{raw}/*-*.png")} - {"base-front", "base-back"})
for name in names:
    best = None
    for tag in TAGS:
        o = overlay(name, tag)
        if o and (best is None or o[0] > best[0] * 1.5):
            best = (o[0], o[1], tag)
        if best and best[0] >= SEEN:
            break
    if not best or best[0] < MIN:
        dropped.append(name)
        continue
    best[1].resize((W, H), Image.LANCZOS).save(f"{out}/{name}.webp", quality=84, method=6)
    kept.append(name)
    print(f"{name:28s} {best[0] * 100:6.3f} %  {best[2] or 'surface'}")

with open(manifest, "w") as f:
    f.write("// Generated by pipeline/exercises/maps.py — muscle-map overlays that exist in public/exercise-maps.\n")
    f.write("export const MAP_OVERLAYS: ReadonlySet<string> = new Set<string>([\n")
    for i in range(0, len(kept), 6):
        f.write("  " + ", ".join(f'"{k}"' for k in kept[i:i + 6]) + ",\n")
    f.write("]);\n")
print(len(kept), "overlays;", len(dropped), "not visible from that side:", " ".join(dropped))
