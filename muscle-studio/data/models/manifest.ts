export function assetsForGender(gender: Gender): AnatomyAssetDefinition[] {
  return ANATOMY_ASSETS.filter((a) => a.gender === gender).sort((a, b) => a.priority - b.priority);
}

/**
 * Pick the asset to display for a gender + view, given which asset files exist.
 * Returns null when no installed asset covers the request.
 */
export function resolveAsset(
  gender: Gender,
  view: ViewId,
  available: ReadonlySet<string>,
): AnatomyAssetDefinition | null {
  const candidates = assetsForGender(gender).filter((a) => available.has(a.id));
  return (
    candidates.find((a) => a.views.includes(view)) ??
    // Fall back to any installed full-body asset for the gender.
    candidates.find((a) => a.views.length > 1) ??
    null
  );
}

export function primaryAssetFor(gender: Gender): AnatomyAssetDefinition {
  const asset = assetsForGender(gender).find((a) => a.views.length === 4);
  if (!asset) throw new Error(`No primary asset configured for ${gender}`);
  return asset;
}
