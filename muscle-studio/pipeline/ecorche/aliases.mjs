// Writes data/exercises/aliases.ts from the name table: part ids of the previous body that
// are one muscle in the Écorché model (links and exercise groups use the part ids).
//   node pipeline/ecorche/aliases.mjs
import { writeFileSync } from "node:fs";
import { MUSCLES } from "./names.mjs";
const map = {};
for (const m of Object.values(MUSCLES)) for (const a of m.aliases) map[a] = m.id;
const body = Object.entries(map).sort().map(([a, id]) => `  "${a}": "${id}",`).join("\n");
writeFileSync("data/exercises/aliases.ts", `// Generated by pipeline/ecorche/aliases.mjs from pipeline/ecorche/names.mjs — do not edit.
/**
 * Muscle ids that name a part of a muscle (the previous body had a mesh per part) and the id
 * of the whole muscle in the Écorché model, which has one mesh for it. Links (\`?muscle=\`),
 * exercise groups and saved selections keep using the part ids: they resolve through this.
 */
export const UNIT_ALIAS: Record<string, string> = {
${body}
};

const PARTS = new Map<string, string[]>();
for (const [part, whole] of Object.entries(UNIT_ALIAS)) PARTS.set(whole, [...(PARTS.get(whole) ?? []), part]);

/** The id under which a muscle exists in a model that has \`has(id)\`: itself, or the muscle it is a part of. */
export function resolveUnit(id: string, has: (id: string) => boolean): string | null {
  if (has(id)) return id;
  const whole = UNIT_ALIAS[id];
  return whole && has(whole) ? whole : null;
}

/** A muscle's id together with the ids of its parts (for looking it up in data keyed by part). */
export function withParts(id: string): string[] {
  return [id, ...(PARTS.get(id) ?? [])];
}
`);
